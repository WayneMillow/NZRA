      <h3 class="subheader">Safety and Clothing</h3>
	  <p>Each team will receive an A4 copy of the map at registration. After planning their route for the day, you must mark your intended route on this map (showing direction of travel, and team number) and hand it in before starting. This route is not binding; you can change course at any time. This “flight plan” is useful as an indicator if you fail to return.</p>
