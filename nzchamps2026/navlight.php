          <p>The function of special-purpose Punches is described in more detail below.</p>
          <ul>
            <li><b>TEST</b> Punch. This is available at Registration for you to try your Tag to see how the system works. It has no effect on your score. If the red light flashes even once, it has worked.</li>
            <li><b>BRIEF</b> Punch. One or more BRIEF Punches will be available shortly before the event start. You will usually find the BRIEF Punch as you enter the Briefing area; hence the name. Officials may inspect your Tag to ensure it is properly fastened on your wrist so it is important that each Tag is registered on one of these Punches BEFORE you start the event.</li>
            <li><b>FINISH</b> Punch. Several of these will be available at the finish line. ALL team members with Tags MUST use one as you finish, as it records your finish time. For a team, the finish time is taken as the time of the last Tag to finish. If you return during the event, you should still use a Finish Punch. It doesn’t matter if you subsequently go out for more checkpoints, as long as you use a FINISH Punch again when you return. Earlier Finish times will be ignored.</li>
            <li><b>DEPART</b> Punch. If you visit the administration area during an event, and use a FINISH Punch when you arrive, you must use a DEPART Punch when you leave again.</li>
