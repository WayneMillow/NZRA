          <h4>WHAT IF SOMETHING GOES WRONG</h4>
          <h5>PUNCH FAILURE</h5>
          <p>If you encounter a Punch which fails to operate, write down its internal 3-letter Code as evidence that you have visited the checkpoint. This 3-letter code is visible through the transparent plastic cover. However, your team will be credited with the visit only if it can be verified that the Punch has indeed failed.</p>
          <p>There is a possibility that the punch has temporarily lost its power. If so, you may have to wait for up to three seconds for a response.</p>
          <h5>TAG FAILURE</h5>
          <p>Again, you can only record the internal 3-letter Code inside each Punch you visit. You can rely on the other Tags in your team to record your visit, but tell the organizers when you finish. Your team will be credited with the visit only if it can be verified that your Tag did indeed fail.</p>      
