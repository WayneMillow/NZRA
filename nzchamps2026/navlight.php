          <h4>Fitting the wrist-bands</h4>
          <p>The wrist-bands are made from a rugged vinyl material and can not be removed from the wrist without breaking them. Wear them quite loosely; you should be able to fit two fingers comfortably between the band and your wrist. Over a 24-hour period, a tight strap will cause irritation.</p>
          <p>Thread the band through your Tag, wrap it around your wrist, then close the clasp through one of the holes in the strap. There is a loose end which you can pull off carefully.</p>
